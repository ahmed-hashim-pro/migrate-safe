const schemaSQL = `
CREATE TABLE accounts (id bigint PRIMARY KEY, name text NOT NULL);
CREATE TABLE orders (
    id bigserial PRIMARY KEY,
    account_id bigint NOT NULL,
    amount_cents integer NOT NULL,
    status text,
    note varchar(100),
    price numeric(10,2),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX orders_created_idx ON orders (created_at);
ALTER TABLE orders ADD CONSTRAINT orders_fk FOREIGN KEY (account_id) REFERENCES accounts (id) NOT VALID;
ALTER TABLE orders ADD CONSTRAINT status_nn CHECK (status IS NOT NULL) NOT VALID;
`

func lintSQL(t *testing.T, pg int, sql string) []Result {
	t.Helper()
	schema, err := sqlparse.Split(schemaSQL)
	if err != nil {
		t.Fatal(err)
	}
	stmts, err := sqlparse.Split(sql)
	if err != nil {
		t.Fatal(err)
	}
	return File(stmts, Options{PG: pg, Schema: ApplySchema(schema, pg)})
}

func effectOn(r Result, table string) (Effect, bool) {
	for _, e := range r.Effects {
		if e.Table == table {
			return e, true
		}
	}
	return Effect{}, false
}

// Each case's expectations were checked against PostgreSQL 16 and 17; the
// integration test re-checks them on every CI run (testdata/corpus.sql).
func TestStatementEffects(t *testing.T) {
	cases := []struct {
		sql     string
		table   string
		lock    Mode
		rewrite bool
		scan    bool
	}{
		{"CREATE INDEX i ON orders (account_id)", "orders", Share, false, true},
		{"CREATE UNIQUE INDEX i ON orders (id, account_id)", "orders", Share, false, true},
		{"CREATE INDEX CONCURRENTLY i ON orders (account_id)", "orders", ShareUpdateExclusive, false, true},
		{"DROP INDEX orders_created_idx", "orders", AccessExclusive, false, false},
		{"DROP INDEX CONCURRENTLY orders_created_idx", "orders", ShareUpdateExclusive, false, false},
		{"REINDEX INDEX orders_created_idx", "orders", Share, false, true},
		{"ALTER TABLE orders ADD COLUMN x uuid DEFAULT gen_random_uuid()", "orders", AccessExclusive, true, true},
		{"ALTER TABLE orders ADD COLUMN x integer NOT NULL DEFAULT 0", "orders", AccessExclusive, false, false},
		{"ALTER TABLE orders ADD COLUMN x timestamptz DEFAULT now()", "orders", AccessExclusive, false, false},
		{"ALTER TABLE orders ADD COLUMN x bigserial", "orders", AccessExclusive, true, true},
		{"ALTER TABLE orders ADD COLUMN x int GENERATED ALWAYS AS (amount_cents * 2) STORED", "orders", AccessExclusive, true, true},
		{"ALTER TABLE orders ADD COLUMN x int GENERATED BY DEFAULT AS IDENTITY", "orders", AccessExclusive, true, true},
		{"ALTER TABLE orders ADD COLUMN x text DEFAULT my_func()", "orders", AccessExclusive, true, true},
		{"ALTER TABLE orders ADD COLUMN x numeric(10,2) DEFAULT 0::numeric(10,2)", "orders", AccessExclusive, false, false},
		{"ALTER TABLE orders ALTER COLUMN amount_cents TYPE bigint", "orders", AccessExclusive, true, true},
		{"ALTER TABLE orders ALTER COLUMN note TYPE varchar(200)", "orders", AccessExclusive, false, false},
		{"ALTER TABLE orders ALTER COLUMN note TYPE varchar(50)", "orders", AccessExclusive, true, true},
		{"ALTER TABLE orders ALTER COLUMN note TYPE text", "orders", AccessExclusive, false, false},
		{"ALTER TABLE orders ALTER COLUMN status TYPE varchar", "orders", AccessExclusive, false, false},
		{"ALTER TABLE orders ALTER COLUMN status TYPE varchar(10)", "orders", AccessExclusive, true, true},
		{"ALTER TABLE orders ALTER COLUMN price TYPE numeric(12,2)", "orders", AccessExclusive, false, false},
		{"ALTER TABLE orders ALTER COLUMN price TYPE numeric(12,3)", "orders", AccessExclusive, true, true},
		{"ALTER TABLE orders ALTER COLUMN amount_cents TYPE integer USING amount_cents + 0", "orders", AccessExclusive, true, true},
		{"ALTER TABLE orders ALTER COLUMN status SET NOT NULL", "orders", AccessExclusive, false, true},
		{"ALTER TABLE orders ALTER COLUMN status DROP NOT NULL", "orders", AccessExclusive, false, false},
		{"ALTER TABLE orders ALTER COLUMN status SET DEFAULT 'new'", "orders", AccessExclusive, false, false},
		{"ALTER TABLE orders ALTER COLUMN status SET STATISTICS 500", "orders", ShareUpdateExclusive, false, false},
		{"ALTER TABLE orders SET (fillfactor = 90)", "orders", ShareUpdateExclusive, false, false},
		{"ALTER TABLE orders ADD CONSTRAINT c CHECK (amount_cents > 0)", "orders", AccessExclusive, false, true},
		{"ALTER TABLE orders ADD CONSTRAINT c CHECK (amount_cents > 0) NOT VALID", "orders", AccessExclusive, false, false},
		{"ALTER TABLE orders ADD CONSTRAINT f FOREIGN KEY (account_id) REFERENCES accounts (id)", "orders", ShareRowExclusive, false, true},
		{"ALTER TABLE orders ADD CONSTRAINT f FOREIGN KEY (account_id) REFERENCES accounts (id)", "accounts", ShareRowExclusive, false, true},
		{"ALTER TABLE orders ADD CONSTRAINT f FOREIGN KEY (account_id) REFERENCES accounts (id) NOT VALID", "accounts", ShareRowExclusive, false, false},
		{"ALTER TABLE orders VALIDATE CONSTRAINT orders_fk", "orders", ShareUpdateExclusive, false, true},
		{"ALTER TABLE orders VALIDATE CONSTRAINT orders_fk", "accounts", RowShare, false, true},
		{"ALTER TABLE orders DROP CONSTRAINT orders_fk", "accounts", AccessExclusive, false, false},
		{"ALTER TABLE orders ADD CONSTRAINT u UNIQUE (id, account_id)", "orders", AccessExclusive, false, true},
		{"ALTER TABLE orders ADD CONSTRAINT u UNIQUE USING INDEX orders_created_idx", "orders", AccessExclusive, false, false},
		{"ALTER TABLE orders RENAME COLUMN note TO memo", "orders", AccessExclusive, false, false},
		{"ALTER TABLE orders DROP COLUMN note", "orders", AccessExclusive, false, false},
		{"ALTER TABLE orders DISABLE TRIGGER ALL", "orders", ShareRowExclusive, false, false},
		{"ALTER TABLE orders SET LOGGED", "orders", AccessExclusive, true, true},
		{"CREATE TRIGGER t BEFORE INSERT ON orders FOR EACH ROW EXECUTE FUNCTION f()", "orders", ShareRowExclusive, false, false},
		{"DROP TRIGGER t ON orders", "orders", AccessExclusive, false, false},
		{"CREATE TABLE refunds (id bigint, order_id bigint REFERENCES orders (id))", "orders", ShareRowExclusive, false, false},
		{"TRUNCATE orders", "orders", AccessExclusive, false, false},
		{"VACUUM FULL orders", "orders", AccessExclusive, true, true},
		{"CLUSTER orders USING orders_created_idx", "orders", AccessExclusive, true, true},
		{"LOCK TABLE orders IN SHARE ROW EXCLUSIVE MODE", "orders", ShareRowExclusive, false, false},
		{"LOCK orders", "orders", AccessExclusive, false, false},
	}
	for _, c := range cases {
		r := lintSQL(t, 17, c.sql)[0]
		if r.Unknown != "" {
			t.Errorf("%s: not analysed: %s", c.sql, r.Unknown)
			continue
		}
		e, ok := effectOn(r, c.table)
		if !ok {
			t.Errorf("%s: no effect on %s (effects: %+v)", c.sql, c.table, r.Effects)
			continue
		}
		if e.Lock != c.lock || e.Rewrite != c.rewrite || e.Scan != c.scan {
			t.Errorf("%s on %s: got %s rewrite=%v scan=%v, want %s rewrite=%v scan=%v",
				c.sql, c.table, e.Lock, e.Rewrite, e.Scan, c.lock, c.rewrite, c.scan)
		}
	}
}

func severities(r Result) string {
	var s []string
	for _, f := range r.Findings {
		s = append(s, f.Severity.String())
	}
	return strings.Join(s, ",")
}

func TestVersionCaveats(t *testing.T) {
	// A constant default is metadata-only from PostgreSQL 11.
	sql := "SET lock_timeout = '1s'; ALTER TABLE orders ADD COLUMN x integer NOT NULL DEFAULT 0"
	if e, _ := effectOn(lintSQL(t, 10, sql)[1], "orders"); !e.Rewrite {
		t.Error("PostgreSQL 10: constant default should rewrite")
	}
	if e, _ := effectOn(lintSQL(t, 11, sql)[1], "orders"); e.Rewrite {
		t.Error("PostgreSQL 11: constant default should not rewrite")
	}
	// From 12, a validated CHECK (col IS NOT NULL) lets SET NOT NULL skip its scan.
	steps := `SET lock_timeout = '1s';
ALTER TABLE orders VALIDATE CONSTRAINT status_nn;
ALTER TABLE orders ALTER COLUMN status SET NOT NULL;`
	if e, _ := effectOn(lintSQL(t, 12, steps)[2], "orders"); e.Scan {
		t.Error("PostgreSQL 12: SET NOT NULL after a validated check should not scan")
	}
	if e, _ := effectOn(lintSQL(t, 11, steps)[2], "orders"); !e.Scan {
		t.Error("PostgreSQL 11: SET NOT NULL always scans")
	}
	// A NOT VALID check is not enough.
	if e, _ := effectOn(lintSQL(t, 17, "ALTER TABLE orders ALTER COLUMN status SET NOT NULL")[0], "orders"); !e.Scan {
		t.Error("an unvalidated check should not let SET NOT NULL skip its scan")
	}
}

func TestSeverities(t *testing.T) {
	cases := []struct{ sql, want string }{
		{"CREATE INDEX i ON orders (account_id)", "DANGER,RISK"},
		{"CREATE INDEX CONCURRENTLY i ON orders (account_id)", ""},
		{"SET lock_timeout = '2s'; CREATE INDEX i ON orders (account_id)", "DANGER"},
		{"ALTER TABLE orders ADD COLUMN x int", "RISK"},
		{"SET lock_timeout = '2s'; ALTER TABLE orders ADD COLUMN x int", ""},
		{"UPDATE orders SET status = 'x'", "DANGER"},
		{"UPDATE orders SET status = 'x' WHERE id = 1", ""},
		{"-- migrate-safe: batch orders.id 1000\nUPDATE orders SET status = 'x' WHERE id >= :lo AND id < :hi", ""},
		{"CREATE TABLE t (id int); CREATE INDEX ti ON t (id)", ""},
		{"VALIDATE", ""},
	}
	for _, c := range cases {
		rs := lintSQL(t, 17, c.sql)
		r := rs[len(rs)-1]
		if got := severities(r); got != c.want {
			t.Errorf("%s:\n got [%s]\nwant [%s]", c.sql, got, c.want)
		}
	}
}

func TestTransactionAccumulates(t *testing.T) {
	rs := lintSQL(t, 17, `SET lock_timeout = '2s';
BEGIN;
ALTER TABLE orders ADD COLUMN x integer;
UPDATE orders SET x = 1;
COMMIT;
UPDATE orders SET x = 2 WHERE id = 1;`)
	upd := rs[3]
	if upd.Held["orders"] != AccessExclusive {
		t.Fatalf("held after UPDATE in transaction = %s, want ACCESS EXCLUSIVE", upd.Held["orders"])
	}
	msg := ""
	for _, f := range upd.Findings {
		if f.Severity == Danger {
			msg = f.Message
		}
	}
	if !strings.Contains(msg, "reads and writes") || !strings.Contains(msg, "earlier in this transaction") {
		t.Errorf("danger message should say reads are blocked by the earlier lock, got %q", msg)
	}
	if rs[5].Held["orders"] != RowExclusive {
		t.Errorf("after COMMIT the held lock should reset, got %s", rs[5].Held["orders"])
	}
}

func TestLockTimeoutTracking(t *testing.T) {
	rs := lintSQL(t, 17, `SET lock_timeout TO 1500;
ALTER TABLE orders ADD COLUMN a int;
BEGIN;
SET LOCAL lock_timeout = '3s';
ALTER TABLE orders ADD COLUMN b int;
COMMIT;
ALTER TABLE orders ADD COLUMN c int;
RESET lock_timeout;
ALTER TABLE orders ADD COLUMN d int;
SET lock_timeout = DEFAULT;`)
	want := map[int]time.Duration{1: 1500 * time.Millisecond, 4: 3 * time.Second, 6: 1500 * time.Millisecond, 8: 0}
	for i, d := range want {
		if rs[i].LockTimeout != d {
			t.Errorf("statement %d (%s): lock_timeout %s, want %s", i, rs[i].Stmt.SQL, rs[i].LockTimeout, d)
		}
	}
}

