func TestParseTimeout(t *testing.T) {
	for in, want := range map[string]time.Duration{"2s": 2 * time.Second, "200ms": 200 * time.Millisecond, "1500": 1500 * time.Millisecond, "1min": time.Minute, "0": 0} {
		got, err := parseTimeout(in)
		if err != nil || got != want {
			t.Errorf("parseTimeout(%q) = %v, %v", in, got, err)
		}
	}
	if _, err := parseTimeout("2 fortnights"); err == nil {
		t.Error("expected an error")
	}
}
